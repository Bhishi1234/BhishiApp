const dictionaries: Record<AppLocale, Record<MessageKey, string>> = {
  en,
  hi,
  mr,
};

export function parseLocale(value: string | null | undefined): AppLocale {
  if (value === "hi" || value === "mr" || value === "en") return value;
  return "en";
}

export function dateLocale(locale: AppLocale) {
  if (locale === "hi") return "hi-IN";
  if (locale === "mr") return "mr-IN";
  return "en-IN";
}

export function t(
  locale: AppLocale,
  key: MessageKey,
  vars?: Record<string, string | number>,
) {
  const dict = dictionaries[locale] ?? dictionaries.en;
  let text = dict[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
